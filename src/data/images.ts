import { blurData } from './blur.generated';

/**
 * Photo lookup. Every item defaults to /menu/<item-id>.webp.
 * To swap a photo, either replace that file or add a one-line override here:
 *   'paneer-tikka': '/menu/real-paneer-tikka.webp',
 */
export const imageOverrides: Record<string, string> = {};

export const itemImage = (id: string) => imageOverrides[id] ?? `/menu/${id}.webp`;
export const blurFor = (id: string): string | undefined => blurData[id];

export const heroImages = [
  { src: '/hero/hero-1.webp', blur: blurData['hero-1'], alt: 'Vegetable biryani in a brass handi' },
  { src: '/hero/hero-2.webp', blur: blurData['hero-2'], alt: 'Gujarati thali with dal, sabzi and rotis' },
  { src: '/hero/hero-3.webp', blur: blurData['hero-3'], alt: 'Paneer butter masala with cream' },
  { src: '/hero/hero-4.webp', blur: blurData['hero-4'], alt: 'Crisp masala dosa with chutneys' },
];

/** 240px thumbnail generated by `npm run thumbs` for any photo stored directly in /menu/. */
export const thumbFor = (src: string) => (/^\/menu\/[^/]+\.webp$/.test(src) ? src.replace('/menu/', '/menu/thumb/') : undefined);
