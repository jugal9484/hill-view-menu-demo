// Downloads placeholder dish photos (Unsplash, free licence), normalises them to
// 600×600 WebP with a faint warm overlay, and writes tiny blur-up previews.
// Swap any photo by dropping a new file into /public/menu/<item-id>.webp.
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const sources = JSON.parse(fs.readFileSync(path.join(root, 'scripts/photo-sources.json'), 'utf8'));
const hero = {
  'hero-1': '1563379091339-03b21ab4a4f8',
  'hero-2': '1589778655375-3e622a9fc91c',
  'hero-3': '1603894584373-5ac82b2ae398',
  'hero-4': '1668236543090-82eba5ee5976',
};
const cache = new Map();
async function get(id, w) {
  const key = id + w;
  if (!cache.has(key)) {
    cache.set(key, fetch(`https://images.unsplash.com/photo-${id}?w=${w}&h=${w}&fit=crop&q=80&auto=format&fm=jpg`)
      .then(async (r) => { if (!r.ok) throw new Error(`${id} ${r.status}`); return Buffer.from(await r.arrayBuffer()); }));
  }
  return cache.get(key);
}
const warm = (s) => Buffer.from(`<svg width="${s}" height="${s}"><rect width="100%" height="100%" fill="#C9A45C" fill-opacity="0.06"/></svg>`);

async function encode(buf, size, out) {
  let q = 74, data;
  do {
    data = await sharp(buf).resize(size, size, { fit: 'cover' }).modulate({ saturation: 1.04 })
      .composite([{ input: warm(size), blend: 'soft-light' }]).webp({ quality: q }).toBuffer();
    q -= 6;
  } while (data.length > 60_000 && q > 30);
  fs.writeFileSync(out, data);
  const tiny = await sharp(buf).resize(12, 12).webp({ quality: 40 }).toBuffer();
  return `data:image/webp;base64,${tiny.toString('base64')}`;
}

const blur = {};
const entries = Object.entries(sources);
for (let i = 0; i < entries.length; i += 8) {
  await Promise.all(entries.slice(i, i + 8).map(async ([item, id]) => {
    blur[item] = await encode(await get(id, 700), 600, path.join(root, 'public/menu', `${item}.webp`));
  }));
}
for (const [name, id] of Object.entries(hero)) {
  blur[name] = await encode(await get(id, 900), 720, path.join(root, 'public/hero', `${name}.webp`));
}
const ts = `// Generated by scripts/fetch-images.mjs — do not edit by hand.\nexport const blurData: Record<string, string> = ${JSON.stringify(blur, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'src/data/blur.generated.ts'), ts);
console.log('images:', Object.keys(blur).length);
await import('./make-thumbs.mjs');
